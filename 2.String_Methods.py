# Program to demonstrate string methods
text = "  Hello Python Programming  "
# Upper method
print("Uppercase:", text.upper())
# Lower method
print("Lowercase:", text.lower())
# Strip method
print("Stripped:", text.strip())
# Split method
print("Split:", text.split())
# Join method
words = ["Hello", "Python"]
print("Joined:", " ".join(words))
# Replace method
print("Replaced:", text.replace("Python", "Java"))
# Find method
print("Find:", text.find("Python"))