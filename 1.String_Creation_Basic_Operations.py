# Program to demonstrate string creation and basic operations
# String creation
str1 = "Hello"
str2 = "Python"
print("First string:", str1)
print("Second string:", str2)
# String concatenation
print("Concatenation:", str1 + " " + str2)
# String repetition
print("Repetition:", str1 * 3)
# String slicing
print("Slicing:", str2[0:3])
print("Negative slicing:", str2[-3:])